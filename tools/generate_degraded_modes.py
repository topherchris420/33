"""Generate docs/DEGRADED_MODES.md by exhausting the ground status model.

Every combination of failed units is evaluated: what still works, and what the
dashboard could tell apart. The output is analytical, computed from a model pinned
to firmware source. It says nothing about how hardware actually fails.
"""

import argparse
from collections import defaultdict
from itertools import combinations
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "Firmware"))

from ground_status import ADVISORIES, capabilities_after, load_model, signature

OUTPUT = ROOT / "docs" / "DEGRADED_MODES.md"


def failure_sets(units):
    for size in range(len(units) + 1):
        yield from (frozenset(combo) for combo in combinations(units, size))


def analyse(model):
    units = [unit["id"] for unit in model["units"]]
    passive, probed = defaultdict(list), defaultdict(list)
    for failed in failure_sets(units):
        passive[tuple(sorted(signature(failed, model).items()))].append(failed)
        probed[tuple(sorted(signature(failed, model, probe=True).items()))].append(failed)
    return {"units": units, "total": 2 ** len(units), "passive": passive, "probed": probed}


def _names(failed):
    return "+".join(sorted(failed)) if failed else "none"


def _single_groups(groups):
    """Single-unit failures the dashboard cannot tell from each other."""
    result = []
    for sets in groups.values():
        singles = sorted(_names(failed) for failed in sets if len(failed) == 1)
        if len(singles) > 1:
            result.append(singles)
    return sorted(result)


def _masked_by(groups, model):
    """For each single failure, the other units whose health it hides."""
    hidden = {}
    for sets in groups.values():
        for failed in sets:
            if len(failed) == 1:
                unit = next(iter(failed))
                covers = {other for candidate in sets if unit in candidate and len(candidate) == 2
                          for other in candidate - {unit}}
                hidden[unit] = sorted(covers)
    return hidden


def render(model):
    analysis = analyse(model)
    units = analysis["units"]
    capabilities = model["capabilities"]
    count = len(capabilities)
    lines = [
        "# Degraded Modes",
        "",
        "Generated by `tools/generate_degraded_modes.py` from `protocol/ground_status_model.json`. Do not edit by hand.",
        "",
        f"**Evidence class: analytical.** This exhausts all {analysis['total']} combinations of {len(units)} failed units in a dependency model pinned to firmware source. It shows what the firmware's structure implies. No fault has been injected on hardware, so every entry's bench evidence is **NOT MEASURED**. See [Ground Status](GROUND_STATUS.md) for how the board uses this.",
        "",
        "## What each single failure leaves",
        "",
        "```mermaid",
        "flowchart LR",
        f'    FULL["All units working<br>{count} of {count} capabilities"]',
    ]
    for unit in units:
        left = capabilities_after({unit}, model)
        lost_safety = [c for c in capabilities if c["safety"] and c["id"] not in left]
        note = f"<br>{len(lost_safety)} safety-related lost" if lost_safety else ""
        lines.append(f'    FULL --> {unit}["{unit} failed<br>{len(left)} of {count} remain{note}"]')
    lines += ["```", "", "`x` means the capability is lost when that unit fails. Rows marked **S** are safety-related.", ""]

    lines.append("| Capability | S | " + " | ".join(units) + " |")
    lines.append("|---|---|" + "---|" * len(units))
    for capability in capabilities:
        cells = " | ".join("x" if unit in capability["requires"] else "" for unit in units)
        lines.append(f"| {capability['name']} | {'**S**' if capability['safety'] else ''} | {cells} |")

    lines += ["", "### Why each dependency holds", "", "| Capability | Reason |", "|---|---|"]
    lines += [f"| {capability['name']} | {capability['why']} |" for capability in capabilities]

    lines += [
        "",
        "## What the dashboard can tell apart",
        "",
        "A fault can only be isolated if it changes what the dashboard observes. Grouping failure sets by observable signature shows the limits. The log-dump probe is the existing `dumplog` command, sent by the operator.",
        "",
        "| Observation | Distinct signatures | Failure sets |",
        "|---|---|---|",
        f"| Passive, packets only | {len(analysis['passive'])} | {analysis['total']} |",
        f"| With the log-dump probe | {len(analysis['probed'])} | {analysis['total']} |",
        "",
        "Single failures that look identical:",
        "",
        "| Observation | Cannot be separated |",
        "|---|---|",
    ]
    for label, key in (("Passive, packets only", "passive"), ("With the log-dump probe", "probed")):
        for group in _single_groups(analysis[key]):
            lines.append(f"| {label} | {', '.join(group)} |")

    lines += ["", "With the probe, a second failure each of these hides from the dashboard:", "", "| After this fails | These can also have failed unnoticed |", "|---|---|"]
    for unit, hidden in _masked_by(analysis["probed"], model).items():
        lines.append(f"| {unit} | {', '.join(hidden) if hidden else 'none'} |")

    lines += ["", "## Channels", "", "| Packet stream | Needs | Reason |", "|---|---|---|"]
    lines += [f"| {channel['name']} | {', '.join(channel['requires'])} | {channel['why']} |" for channel in model["channels"]]

    lines += ["", "## Capabilities the firmware does not have", "",
              "Pinned so that adding one fails a test and forces this model and the board to be updated.", "",
              "| Missing | Why it matters |", "|---|---|"]
    lines += [f"| {item['name']} | {item['why']} |" for item in model["absent_capabilities"]]

    lines += ["", "## Advisories", "", "| ID | Level | Meaning |", "|---|---|---|"]
    lines += [f"| `{advisory_id}` | {level} | {detail} |" for advisory_id, (level, detail) in ADVISORIES.items()]

    lines += ["", "## Not modeled", ""]
    lines += [f"- {item}" for item in model["not_modeled"]]
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate docs/DEGRADED_MODES.md.")
    parser.add_argument("--check", action="store_true", help="Fail if the generated document is stale")
    args = parser.parse_args()
    content = render(load_model())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"stale: {OUTPUT}")
            return 1
        print("Degraded modes document is up to date.")
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
