function renderExplain(id) {
  const host = $("#ck-explain");
  const back = $("#ck-back");
  back.disabled = !id;
  for (const b of $$("[data-display]")) b.setAttribute("aria-pressed", String(b.dataset.display === id));
  if (!id) {
    clear(host,
      h("div", { class: "panel-head" }, h("h4", {}, "The exhibit"), categoryBadge("historical", "generic")),
      h("div", { class: "panel-body" },
        h("p", {}, "Select a display in the diorama — or with the buttons below — to fly the camera to it and read how engineers decide what goes on it."),
        h("p", { class: "small muted" }, "Raw sensor observations, derived estimates, displays, warnings, and operator interpretation are different things. The exhibit shows the display end; the panel further down shows the whole chain."),
        readabilityNote()));
    return;
  }
  const e = EXPLAIN[id];
  const body = h("div", { class: "panel-body" });
  clear(host, h("div", { class: "panel-head" }, h("h4", {}, e.title), categoryBadge("historical", "generic")), body);
  depthTabs(body, [
    { label: "Introduction", content: h("p", {}, e.intro) },
    { label: "Engineering", content: (panel) => { panel.append(h("p", {}, e.eng[0]), eq(e.eng[1]), h("p", {}, e.eng[2])); } },
    { label: "Research", content: (panel) => panel.append(
      h("p", {}, "This exhibit is an original, generic illustration. It reproduces no text, figure, symbology, or display format from the supplied F-117A supplement, whose distribution statement does not permit that."),
      h("p", { class: "small" }, "Drawing code: ", h("code", {}, "lab/js/instruments/symbology.js"), " · flight values: a synthetic generator, ", h("code", {}, "flightState(t)"), ".")) },
  ]);
  body.append(readabilityNote(id));
}

function readabilityNote(id) {
  const level = store.get().declutter;
  const lists = id ? { [id]: elementsAt(id, level) } : Object.fromEntries(Object.keys(DECLUTTER).map((k) => [k, elementsAt(k, level)]));
  const total = Object.values(lists).reduce((s, l) => s + l.length, 0);
  const max = Object.values(DECLUTTER).reduce((s, l) => s + l.length, 0);
  return h("div", { class: "ck-read" },
    h("p", { class: "label" }, `Declutter level ${level} · ${total} element${total === 1 ? "" : "s"} drawn${id ? "" : ` of ${max}`}`),
    h("ul", { class: "small" }, Object.entries(lists).map(([k, l]) => h("li", {}, h("b", {}, { hud: "Head-up", map: "Navigation", status: "Status" }[k]), ": ", l.join(", ")))),
    h("p", { class: "small muted" }, level <= 2 ? "Sparse: fast to read, but less context — the operator must remember what is hidden." : level >= 5 ? "Everything on: maximum context, slowest search. Visual search time grows with the number of competing items." : "Balanced: the essentials plus supporting context."));
}

// ---------- boot ----------
async function boot() {
  mountConfiguration($("#configuration-compare"));
  mountUSBMonitor($("#usb-monitor-report"));
  mountAltimeter($("#altimeter-review"));
  // Declutter
  const dec = $("#declutter");
  dec.addEventListener("input", () => { store.setDeclutter(Number(dec.value)); $("#declutter-out").textContent = `level ${dec.value}`; renderExplain(cockpit?.selected ?? null); });
  syncRange(dec);

  let cockpit = null;
  const vp = $("#ck-viewport");
  if (webglAvailable()) {
    try {
      const { mountCockpit } = await import("./cockpit.js");
      cockpit = mountCockpit({ viewport: vp, store, onSelect: (id) => { renderExplain(id); if (id) announce(`Viewing the ${EXPLAIN[id].title.toLowerCase()}`); } });
    } catch (err) {
      console.warn("cockpit exhibit failed", err);
    }
  }
  if (!cockpit) {
    vp.replaceChildren(h("div", { class: "fallback-2d" }, h("p", {}, "WebGL is unavailable, so the 3D diorama cannot run. The three displays are drawn flat instead."), h("div", { class: "ck-flat", id: "ck-flat" })));
    const { drawHUD, drawMap, drawStatus } = await import("./symbology.js");
    const flat = $("#ck-flat");
    const mk = (fn) => { const c = h("canvas", { width: 512, height: 512 }); flat.append(c); return c.getContext("2d"); };
    const [a, b, c] = [mk(), mk(), mk()];
    const paint = () => { const st = store.get(), s = st.displayState; a.fillStyle = "#03070b"; a.fillRect(0, 0, 512, 512); drawHUD(a, 512, 512, s, st.declutter, { flags: { attitudeLost: st.sources.inertial.state === "unavailable", attitude: st.sources.inertial.state, speed: st.sources.airdata.state, altitude: st.sources.airdata.state } }); drawMap(b, 512, 512, s, st.declutter, { navFlag: st.sources.gnss.state }); drawStatus(c, 512, 512, st.messages, st.declutter, st.time); };
    store.subscribe(paint); paint();
  }
  for (const b of $$("[data-display]")) b.addEventListener("click", () => { if (cockpit) cockpit.select(b.dataset.display); else renderExplain(b.dataset.display); });
  $("#ck-back").addEventListener("click", () => { if (cockpit) cockpit.select(null); else renderExplain(null); });
  renderExplain(null);

  // Information architecture
  const ia = mountInfoArch({ root: $("#ia-root"), preview: $("#ia-preview"), store });
  const iaBody = $("#ia-depth");
  depthTabs(iaBody, [
    { label: "Introduction", content: h("div", {},
      h("p", {}, "A number on a display is the last link of a chain. A sensor makes a raw observation; software checks it and turns it into an estimate of something you care about; the display draws that estimate; monitoring logic may raise an alert; and a person decides what it means. Each link can fail differently."),
      h("p", {}, "Toggle the sources above. ", h("b", {}, "Missing"), " means one expected sample did not arrive. ", h("b", {}, "Stale"), " means the last good value is older than it is allowed to be. ", h("b", {}, "Inconsistent"), " means two independent sources disagree, and the system cannot know which is right. ", h("b", {}, "Unavailable"), " means there is nothing at all.")) },
    { label: "Engineering", content: (panel) => panel.append(
      h("p", {}, "Raw observation → estimate. Barometric altitude, for example, is not measured: it is computed from static pressure with the International Standard Atmosphere troposphere model,"),
      eq("h=\\frac{T_0}{L}\\left[1-\\left(\\frac{p_s}{p_0}\\right)^{R L / g_0}\\right],\\quad T_0=288.15\\,\\mathrm{K},\\ L=0.0065\\,\\mathrm{K/m},\\ p_0=101\\,325\\,\\mathrm{Pa}"),
      h("p", {}, "with R = 287.05 J·kg⁻¹·K⁻¹ and g₀ = 9.80665 m·s⁻², so a pressure error becomes an altitude error, and a non-standard day becomes a bias. Validity is a rule, not a feeling:"),
      eq("\\text{valid}(t)=\\big[\\,t-t_{\\text{last}}\\le T_{\\text{valid}}\\,\\big]\\ \\wedge\\ \\big[\\,x_{\\min}\\le x\\le x_{\\max}\\,\\big]\\ \\wedge\\ \\big[\\,|\\dot x|\\le \\dot x_{\\max}\\,\\big]"),
      h("p", {}, "and a comparator flags disagreement between independent estimates when"),
      eq("|\\hat x_1-\\hat x_2|>\\delta,\\qquad \\delta \\approx k\\sqrt{\\sigma_1^2+\\sigma_2^2}"),
      h("p", {}, "where σ₁, σ₂ are the estimates' stated uncertainties. A comparator can detect disagreement; it cannot, by itself, say which source is wrong — that is why the operator stage exists.")) },
    { label: "Terms", content: h("dl", { class: "kv ia-terms" },
      h("dt", {}, "Raw observation"), h("dd", {}, "What the sensor actually produced: a pressure, an angular rate, a pseudorange. Has units and noise, not meaning."),
      h("dt", {}, "Derived estimate"), h("dd", {}, "A quantity computed from observations through a model, with an uncertainty and an age: altitude, attitude, position."),
      h("dt", {}, "Display"), h("dd", {}, "A rendering of an estimate plus its validity. Drawing an invalid value normally is a design defect."),
      h("dt", {}, "Warning / alert"), h("dd", {}, "Output of monitoring logic comparing estimates with thresholds or with each other. It is itself an estimate that can be wrong."),
      h("dt", {}, "Interpretation"), h("dd", {}, "The person's belief and decision. The goal of the whole chain is that this matches reality.")) },
  ]);

  // Stale ages grow in real time; the preview attitude moves gently.
  let last = performance.now();
  const motion = !reducedMotion();
  setInterval(() => {
    const now = performance.now(), dt = (now - last) / 1000; last = now;
    store.tick(dt);
    if (motion) ia.tick(dt); else ia.paint();
  }, 250);

  // Dependencies
  mountGeneric({ svgHost: $("#dep-generic"), readout: $("#dep-generic-readout"), resetBtn: $("#dep-generic-reset") });
  const model = await canonical.groundStatus();
  mountGroundStatus({ model, unitsHost: $("#gs-units"), resultHost: $("#gs-result"), resetBtn: $("#gs-reset") });
  document.body.dataset.ready = "true";
}

boot().catch((err) => {
  console.error(err);
  $("#main").prepend(h("div", { class: "notice warn wrap" }, `The instrumentation lab could not load: ${err.message}`));
});
