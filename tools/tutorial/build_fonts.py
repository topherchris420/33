"""Subset the vendored OFL fonts and embed them for the tutorial player.

Courier Prime (typewriter body text and commands) and Barlow Condensed
(section headings) are vendored with their SIL Open Font License files in
assets/tutorial/fonts/. The film draws on a canvas, so the fonts are embedded
as base64 WOFF2 in assets/tutorial/fonts.js: no network, no CDN, and the page
still works when opened straight from disk.

    python tools/tutorial/build_fonts.py   (needs fonttools and brotli)
"""
import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "assets" / "tutorial" / "fonts"
FACES = [
    ("P33Mono", "CourierPrime-Regular.ttf"),
    ("P33MonoBold", "CourierPrime-Bold.ttf"),
    ("P33Cond", "BarlowCondensed-SemiBold.ttf"),
    ("P33CondMedium", "BarlowCondensed-Medium.ttf"),
]
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + "–—…·°±²≥≤“”‘’•×é"


def main():
    out = ["/* Generated by tools/tutorial/build_fonts.py. Subsets of Courier Prime and",
           " * Barlow Condensed, (c) their authors, SIL Open Font License 1.1 — see",
           " * assets/tutorial/fonts/*-OFL.txt. */",
           "window.P33T_FONTS = {"]
    for family, name in FACES:
        font = TTFont(FONTS / name)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["kern", "liga"]
        sub = subset.Subsetter(options)
        sub.populate(text=TEXT)
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        data = base64.b64encode(buf.getvalue()).decode("ascii")
        out.append(f'  "{family}": "{data}",')
        print(f"{family}: {len(buf.getvalue())} bytes")
    out.append("};")
    (ROOT / "assets" / "tutorial" / "fonts.js").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
